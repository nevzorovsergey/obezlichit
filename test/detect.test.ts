import { describe, expect, it } from "vitest";
import { detect, isFio } from "../src/core/detect/detect";
import { fioReplacement, initialsReplacement } from "../src/core/synth/fio";
import { innComplete, uinControlDigit } from "../src/core/synth/checksums";

// Синтетический текст в формате постановления ЦАФАП. Номера и имена вымышлены.
const uinBody = "1065269226120000123";
const UIN = uinBody + uinControlDigit(uinBody);
const INN_FL = innComplete("5001007322");
const TEXT_FL = `КОПИЯ ПОСТАНОВЛЕНИЕ ${UIN}
Я, Государственный инспектор отдела МТУ Ространснадзора Сидорова Анна Павловна, рассмотрев материалы,
водитель, управляя ТС КАМАЗ 65115, государственный регистрационный знак (далее - ГРЗ) K412TC69, в составе
разрешения на движение ТС с ГРЗ К412ТС69 за период
Собственником (владельцем) данного ТС, в соответствии со свидетельством о регистрации ТС №9900123456, на
момент фиксации нарушения является Петров Иван Сергеевич Дата рождения: 01.02.1980 ИНН ФЛ: ${INN_FL} Адрес регистрации: 141400, Г.ХИМКИ, УЛ. ЛЕСНАЯ, Д. 7, КВ. 12
Руководствуясь ч.1 ст.2.6.1 КоАП РФ,
единый казначейский счет: 40102810545370000045, УИН: ${UIN}.
Владелец: Сидорова Анна Павловна
А.П. Сидорова
Директор: ИВАНОВ ПЁТР АЛЕКСЕЕВИЧ
Дело об АПН 11121400999 от 13.08.2026`;

const byKind = (text: string) => {
  const m = new Map<string, string[]>();
  for (const f of detect(text)) m.set(f.kind, [...(m.get(f.kind) ?? []), f.value]);
  return m;
};

describe("detect — постановление на физлицо (синтетика)", () => {
  const k = byKind(TEXT_FL);
  it("УИН — оба вхождения, счёт казначейства — нет", () => {
    expect(k.get("uin")).toEqual([UIN, UIN]);
  });
  it("ГРЗ латиницей и кириллицей", () => {
    expect(k.get("plate")).toEqual(["K412TC69", "К412ТС69"]);
  });
  it("любое ФИО: собственник, инспектор, директор в верхнем регистре; инициалы", () => {
    expect(k.get("fio")).toEqual(["Сидорова Анна Павловна", "Петров Иван Сергеевич", "Сидорова Анна Павловна", "ИВАНОВ ПЁТР АЛЕКСЕЕВИЧ"]);
    expect(k.get("initials")).toEqual(["А.П. Сидорова"]);
  });
  it("СТС, дата рождения, ИНН ФЛ, адрес, номер дела", () => {
    expect(k.get("sts")).toEqual(["9900123456"]);
    expect(k.get("date")).toEqual(["01.02.1980"]);
    expect(k.get("inn")).toEqual([INN_FL]);
    expect(k.get("address")).toEqual(["141400, Г.ХИМКИ, УЛ. ЛЕСНАЯ, Д. 7, КВ. 12"]);
    expect(k.get("case")).toEqual(["11121400999"]);
  });
  it("не принимает за ФИО названия и топонимы", () => {
    expect(isFio("Государственный инспектор Приволжского")).toBe(false);
    expect(isFio("МУНИЦИПАЛЬНЫЙ ОКРУГ АЛЕКСЕЕВСКИЙ")).toBe(false);
    expect(isFio("Бугульма Бугуруслан Бузулук")).toBe(false);
  });
});

describe("detect — юрлицо", () => {
  it("наименование собственника остаётся owner, не fio", () => {
    const k = byKind("является ООО \"ГРУЗ ТЕСТ\" Дата регистрации: 19.07.2002 ИНН ЮЛ: " + innComplete("771234567"));
    expect(k.get("owner")).toEqual(["ООО \"ГРУЗ ТЕСТ\""]);
    expect(k.get("fio")).toBeUndefined();
  });
});

describe("заглушки ФИО", () => {
  it.each([
    ["Петров Иван Сергеевич", "Тестов Тест Тестович"],
    ["ИВАНОВ ПЁТР АЛЕКСЕЕВИЧ", "ТЕСТОВ ТЕСТ ТЕСТОВИЧ"],
    ["Анна Павловна Сидорова", "Тест Тестович Тестов"],
  ])("%s → %s", (a, b) => expect(fioReplacement(a)).toBe(b));
  it.each([
    ["А.П. Сидорова", "Т.Т. Тестов"],
    ["Е. Ю. Фомина", "Т. Т. Тестов"],
    ["Сидорова А.П.", "Тестов Т.Т."],
  ])("%s → %s", (a, b) => expect(initialsReplacement(a)).toBe(b));
});
